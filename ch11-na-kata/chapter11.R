# ── block 01 ────────────────────────────────────────
library(tidyverse)
u <- read_csv("uriage.csv", show_col_types = FALSE)
u

# ── block 03 ────────────────────────────────────────
u <- read_csv("uriage.csv", na = c("", "NA", "-"), show_col_types = FALSE)
u

# ── block 04 ────────────────────────────────────────
read_csv("uriage.csv", show_col_types = FALSE) |>
  mutate(売上 = as.numeric(売上))

# ── block 05 ────────────────────────────────────────
sum(u$売上)

# ── block 06 ────────────────────────────────────────
c(mean(u$売上), max(u$売上), sd(u$売上))

# ── block 07 ────────────────────────────────────────
u$売上 > 1000000

# ── block 08 ────────────────────────────────────────
NA == NA

# ── block 09 ────────────────────────────────────────
u$売上 == NA

# ── block 10 ────────────────────────────────────────
is.na(u$売上)

# ── block 11 ────────────────────────────────────────
c(NA & FALSE, NA | TRUE, NA & TRUE, NA | FALSE)

# ── block 12 ────────────────────────────────────────
u |>
  group_by(店舗) |>
  summarise(合計 = sum(売上, na.rm = TRUE),
            平均 = mean(売上, na.rm = TRUE))

# ── block 13 ────────────────────────────────────────
u |>
  group_by(店舗) |>
  summarise(合計 = sum(売上, na.rm = TRUE),
            平均 = mean(売上, na.rm = TRUE),
            行数 = n(),
            欠損 = sum(is.na(売上)))

# ── block 14 ────────────────────────────────────────
u |>
  mutate(売上 = coalesce(売上, 0)) |>
  group_by(店舗) |>
  summarise(平均 = mean(売上))

# ── block 15 ────────────────────────────────────────
u |> filter(売上 >= 800000)

# ── block 16 ────────────────────────────────────────
u |> filter_out(売上 >= 800000)

# ── block 17 ────────────────────────────────────────
u |> filter(売上 >= 800000 | is.na(売上))

# ── block 18 ────────────────────────────────────────
u |>
  mutate(規模 = case_when(売上 >= 1500000 ~ "大",
                          売上 >=  900000 ~ "中",
                          .default = "小")) |>
  select(店舗, 月, 売上, 規模)

# ── block 19 ────────────────────────────────────────
u |>
  mutate(規模 = case_when(is.na(売上)      ~ "未報告",
                          売上 >= 1500000 ~ "大",
                          売上 >=  900000 ~ "中",
                          .default = "小")) |>
  count(規模)

# ── block 20 ────────────────────────────────────────
if_else(u$売上 >= 1000000, "大", "小", missing = "不明")

# ── block 21 ────────────────────────────────────────
u |>
  group_by(区分) |>
  summarise(店舗数 = n_distinct(店舗), 行数 = n())

# ── block 22 ────────────────────────────────────────
count(u, 区分)

