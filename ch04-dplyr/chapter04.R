# ── block 01 ────────────────────────────────────────
library(tidyverse)
sales <- read_csv("sales.csv")

# ── block 02 ────────────────────────────────────────
select(sales, 店舗, 売上)

# ── block 03 ────────────────────────────────────────
select(sales, -日付)

# ── block 04 ────────────────────────────────────────
filter(sales, 店舗 == "新宿店")

# ── block 05 ────────────────────────────────────────
filter(sales, 店舗 == "新宿店", 売上 >= 1500000)

# ── block 06 ────────────────────────────────────────
filter(sales, 売上 < 600000 | 売上 >= 2000000)

# ── block 07 ────────────────────────────────────────
filter(sales, カテゴリ %in% c("家電", "食品"))

# ── block 08 ────────────────────────────────────────
filter(sales, カテゴリ %notin% c("家電", "食品"))

# ── block 09 ────────────────────────────────────────
filter_out(sales, カテゴリ %in% c("家電", "食品"))

# ── block 10 ────────────────────────────────────────
kaiin <- tibble(
  名前 = c("佐藤", "鈴木", "高橋"),
  会員区分 = c("ゴールド", NA, "一般")
)
kaiin |> filter(会員区分 != "ゴールド")

# ── block 11 ────────────────────────────────────────
kaiin |> filter_out(会員区分 == "ゴールド")

# ── block 12 ────────────────────────────────────────
arrange(sales, 売上)

# ── block 13 ────────────────────────────────────────
arrange(sales, desc(売上))

# ── block 14 ────────────────────────────────────────
mutate(sales, 売上千円 = 売上 / 1000)

# ── block 15 ────────────────────────────────────────
mutate(sales, 達成 = if_else(売上 >= 1000000, "達成", "未達"))

# ── block 16 ────────────────────────────────────────
sales |>
  mutate(地域 = recode_values(店舗,
    "新宿店" ~ "東京",
    "大阪店" ~ "大阪",
    "オンライン" ~ "全国"
  )) |>
  distinct(店舗, 地域)

# ── block 17 ────────────────────────────────────────
sales |>
  mutate(地域 = recode_values(店舗, "新宿店" ~ "東京")) |>
  distinct(店舗, 地域)

# ── block 18 ────────────────────────────────────────
sales |>
  mutate(店舗2 = replace_values(店舗, "オンライン" ~ "EC")) |>
  distinct(店舗, 店舗2)

# ── block 19 ────────────────────────────────────────
mutate(sales, ランク = case_when(
  売上 >= 2000000 ~ "S",
  売上 >= 1000000 ~ "A",
  .default = "B"
))

# ── block 20 ────────────────────────────────────────
summarise(sales, 合計 = sum(売上), 平均 = mean(売上))

# ── block 21 ────────────────────────────────────────
sales |>
  group_by(店舗) |>
  summarise(合計 = sum(売上))

# ── block 22 ────────────────────────────────────────
sales |>
  group_by(店舗, カテゴリ) |>
  summarise(合計 = sum(売上))

# ── block 23 ────────────────────────────────────────
sales |>
  summarise(合計 = sum(売上), .by = 店舗)

# ── block 24 ────────────────────────────────────────
sales |>
  summarise(合計 = sum(売上), .by = c(店舗, カテゴリ))

# ── block 25 ────────────────────────────────────────
count(sales, カテゴリ)

# ── block 26 ────────────────────────────────────────
slice_max(sales, 売上, n = 3)

# ── block 30 ────────────────────────────────────────
store_cat <- sales |>
  group_by(店舗, カテゴリ) |>
  summarise(合計 = sum(売上))
store_cat |> mutate(構成比 = 合計 / sum(合計))

# ── block 31 ────────────────────────────────────────
store_cat |>
  ungroup() |>
  mutate(構成比 = 合計 / sum(合計))

# ── block 32 ────────────────────────────────────────
sales |>
  mutate(月 = month(日付)) |>
  summarise(売上合計 = sum(売上), .by = c(月, 店舗)) |>
  filter(店舗 == "新宿店")

