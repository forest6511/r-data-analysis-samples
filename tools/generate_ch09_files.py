#!/usr/bin/env python3
"""第9章（文字列処理と正規表現）用サンプルの決定的生成（乱数不使用）

実務で届く「表記が揃っていない」列を再現する。本文は
「見た目が同じでも別の文字列である」ことを見せるので、
差が入る箇所を意図的に作り、それ以外は揃える。

- kokyaku.csv : 顧客マスタ。全角/半角・空白・ハイフン・丸数字が混在
- juchu.csv   : 受注明細。商品コードの体裁が揃っていない
"""
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent  # repo のルート（データはここに置く）
CH09 = ROOT / "ch09"
CH09.mkdir(exist_ok=True)

# 見た目では区別できない差を入れる:
#   - 全角数字（１２３）と半角数字（123）
#   - 全角スペース（　）と半角スペース
#   - 全角ハイフン（－ U+FF0D）と半角ハイフン（-）
#   - 末尾の余分な空白
KOKYAKU = [
    ("顧客ID", "顧客名", "電話番号", "郵便番号", "メモ"),
    ("C001", "山田 太郎", "03-1234-5678", "160-0023", "初回取引"),
    ("C002", "佐藤　花子", "０３－２２２２－３３３３", "1600023", "請求先変更あり"),
    ("C003", "鈴木一郎 ", "03(3333)4444", "〒160-0023", ""),
    ("C004", "TANAKA Jiro", "090-1111-2222", "160-0023", "英字表記"),
    ("C005", "高橋 　次郎", "0312345678", "160‑0023", "全角混じり"),
]

JUCHU = [
    ("受注ID", "商品コード", "数量", "備考"),
    ("J-1001", "AB-0012", "3", "通常"),
    ("J-1002", "ab-0012", "1", "小文字で登録された"),
    ("J-1003", "AB0012", "5", "ハイフンなし"),
    ("J-1004", "ＡＢ－００１２", "2", "全角で登録された"),
    ("J-1005", "CD-0034", "4", "通常"),
]


def write(rows, path):
    text = "\n".join(",".join(r) for r in rows) + "\n"
    path.write_text(text, encoding="utf-8", newline="")


for _d in (ROOT, CH09):
    write(KOKYAKU, _d / "kokyaku.csv")
for _d in (ROOT, CH09):
    write(JUCHU, _d / "juchu.csv")
print("wrote", CH09 / "kokyaku.csv", CH09 / "juchu.csv")
