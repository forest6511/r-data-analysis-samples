#!/usr/bin/env python3
"""第10章（日付・時刻・和暦・年度）用サンプルの決定的生成（乱数不使用）

実務で届く「日付が日付として読めない」列を再現する。

- keiyaku.csv : 契約台帳。和暦・スラッシュ・ドット・全角が混在する日付列
- access.csv  : アクセスログ。日時が文字列で、タイムゾーンの記載がない
"""
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent  # repo のルート（データはここに置く）
CH10 = ROOT / "ch10"
CH10.mkdir(exist_ok=True)

# 日付表記のばらつきを意図的に作る:
#   令和6年4月1日 / R6.4.1 / 2026/4/1 / 2026.4.1 / ２０２６年４月１日
KEIYAKU = [
    ("契約ID", "契約日", "契約金額", "担当"),
    ("K-001", "令和8年4月1日", "1280000", "山田"),
    ("K-002", "R8.5.15", "940000", "佐藤"),
    ("K-003", "2026/6/1", "763000", "鈴木"),
    ("K-004", "2026.7.20", "1528000", "山田"),
    ("K-005", "平成31年4月1日", "881000", "高橋"),
    ("K-006", "令和1年5月1日", "455000", "佐藤"),
]

ACCESS = [
    ("記録ID", "発生日時", "画面", "秒数"),
    ("A-01", "2026-04-01 09:15:00", "検索", "12"),
    ("A-02", "2026-04-01 23:50:00", "詳細", "35"),
    ("A-03", "2026-04-02 00:10:00", "検索", "8"),
    ("A-04", "2026-12-31 23:59:00", "購入", "44"),
    ("A-05", "2027-01-01 00:05:00", "購入", "27"),
]


def write(rows, path):
    text = "\n".join(",".join(r) for r in rows) + "\n"
    path.write_text(text, encoding="utf-8", newline="")


for _d in (ROOT, CH10):
    write(KEIYAKU, _d / "keiyaku.csv")
for _d in (ROOT, CH10):
    write(ACCESS, _d / "access.csv")
print("wrote", CH10 / "keiyaku.csv", CH10 / "access.csv")
